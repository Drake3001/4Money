"""Install repository hooks only when no existing hook configuration conflicts."""

import subprocess
import sys
from pathlib import Path

HOOKS = ("pre-commit", "prepare-commit-msg", "commit-msg")


def main():
    root = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
    configured = subprocess.run(["git", "config", "--get", "core.hooksPath"], capture_output=True, text=True, cwd=root)
    if configured.returncode == 0:
        print("core.hooksPath is configured; resolve it before installing repository hooks.", file=sys.stderr)
        return 1
    if configured.returncode != 1:
        print("Unable to inspect Git hook configuration.", file=sys.stderr)
        return 1
    hook_dir = Path(subprocess.check_output(["git", "rev-parse", "--git-path", "hooks"], cwd=root, text=True).strip())
    if not hook_dir.is_absolute():
        hook_dir = root / hook_dir
    for name in HOOKS:
        hook = hook_dir / name
        if hook.exists() and (not hook.is_file() or "# File generated by pre-commit" not in hook.read_text(errors="replace")):
            print(f"Existing {name} hook found; installation stopped without overwriting it.", file=sys.stderr)
            return 1
    return subprocess.run([sys.executable, "-m", "pre_commit", "install"], cwd=root).returncode


if __name__ == "__main__":
    sys.exit(main())
