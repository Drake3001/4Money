public sealed class PostgresFactAttribute : FactAttribute
{
	public PostgresFactAttribute()
	{
		if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("TEST_POSTGRES_CONNECTION_STRING")) &&
			!string.Equals(Environment.GetEnvironmentVariable("CI"), "true", StringComparison.OrdinalIgnoreCase))
			Skip = "Set TEST_POSTGRES_CONNECTION_STRING to a disposable PostgreSQL server; each test creates and drops its own database.";
	}
}

public sealed class PostgresTheoryAttribute : TheoryAttribute
{
	public PostgresTheoryAttribute()
	{
		Skip = new PostgresFactAttribute().Skip;
	}
}

public abstract class PostgresFixture : IAsyncLifetime
{
	protected static readonly Guid AnnaId = Guid.Parse("10000000-0000-0000-0000-000000000001");
	protected const string Password = "TestPassword1!";
	private readonly string _databaseName = "user_tests_" + Guid.NewGuid().ToString("N");
	private string? _maintenance;
	private bool _created;
	protected string ConnectionString { get; private set; } = "";
	protected RecordingEmailSender Email { get; } = new();

	public async Task InitializeAsync()
	{
		_maintenance = Environment.GetEnvironmentVariable("TEST_POSTGRES_CONNECTION_STRING");
		if (string.IsNullOrWhiteSpace(_maintenance))
			throw new InvalidOperationException("TEST_POSTGRES_CONNECTION_STRING is required in CI. Integration tests must not silently skip.");
		await using var admin = new NpgsqlConnection(_maintenance);
		await admin.OpenAsync();
		await using (var command = new NpgsqlCommand($"CREATE DATABASE {_databaseName}", admin))
			await command.ExecuteNonQueryAsync();
		_created = true;
		ConnectionString = new NpgsqlConnectionStringBuilder(_maintenance) { Database = _databaseName, Pooling = false }.ConnectionString;
		await using var connection = new NpgsqlConnection(ConnectionString);
		await connection.OpenAsync();
		foreach (var file in new[] { "01-schemas.sql", "02-tables.sql" })
			await ExecuteFileAsync(connection, file);
		await using (var context = new AppDbContext(new DbContextOptionsBuilder<AppDbContext>().UseNpgsql(ConnectionString).Options))
		{
			await context.Database.MigrateAsync();
			Assert.Empty(await context.Database.GetPendingMigrationsAsync());
			Assert.False(context.Database.HasPendingModelChanges());
		}
		await ExecuteFileAsync(connection, "seed_local.sql");
	}

	private static async Task ExecuteFileAsync(NpgsqlConnection connection, string file)
	{
		var sql = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "Baseline", file));
		await using var command = new NpgsqlCommand(sql, connection);
		await command.ExecuteNonQueryAsync();
	}

	public async Task DisposeAsync()
	{
		if (!_created)
			return;
		await using var admin = new NpgsqlConnection(_maintenance);
		await admin.OpenAsync();
		// The name is generated by this fixture; the configured database is never dropped.
		await using var command = new NpgsqlCommand($"DROP DATABASE IF EXISTS {_databaseName} WITH (FORCE)", admin);
		await command.ExecuteNonQueryAsync();
	}

	protected UserDbContext OpenDatabase() => new(new DbContextOptionsBuilder<UserDbContext>().UseNpgsql(ConnectionString).Options);

	protected async Task SetPasswordAsync(Guid userId)
	{
		await using var context = OpenDatabase();
		var user = await context.Users.SingleAsync(u => u.Id == userId);
		user.PasswordHash = new PasswordHasher<Models.User>().HashPassword(user, Password);
		await context.SaveChangesAsync();
	}

	protected async Task<TestHost> StartHostAsync(Action<IServiceCollection>? configureServices = null)
	{
		var builder = WebApplication.CreateBuilder();
		builder.WebHost.UseTestServer();
		builder.Logging.ClearProviders();
		builder.Configuration.AddInMemoryCollection(new Dictionary<string, string?>
		{
			["UserAuthentication:SigningKey"] = "integration-test-signing-key-at-least-32-bytes"
		});
		builder.Services.AddHttpContextAccessor();
		builder.Services.AddScoped<ICurrentUser, HttpCurrentUser>();
		builder.Services.AddControllers().AddApplicationPart(typeof(UsersController).Assembly);
		builder.Services.AddUserAuthentication(builder.Configuration);
		builder.Services.AddDbContext<UserDbContext>(options => options.UseNpgsql(ConnectionString));
		builder.Services.AddScoped<IUserRepository, UserRepository>();
		builder.Services.AddScoped<IUserTokenRepository, UserTokenRepository>();
		builder.Services.AddScoped<IPasswordHasher<Models.User>, PasswordHasher<Models.User>>();
		builder.Services.AddSingleton<IUserTokenGenerator, UserTokenGenerator>();
		builder.Services.AddSingleton<IEmailSender>(Email);
		builder.Services.AddScoped<IUserRegistrationService, UserRegistrationService>();
		builder.Services.AddScoped<IEmailConfirmationService, EmailConfirmationService>();
		builder.Services.AddScoped<IUserProfileService, UserProfileService>();
		builder.Services.AddScoped<IEmailChangeService, EmailChangeService>();
		builder.Services.AddScoped<IPasswordResetService, PasswordResetService>();
		builder.Services.AddScoped<IAccountDeactivationService, AccountDeactivationService>();
		builder.Services.AddOptions<EmailConfirmationOptions>();
		builder.Services.AddOptions<EmailChangeOptions>();
		builder.Services.AddOptions<PasswordResetOptions>();
		builder.Services.AddOptions<AccountDeactivationOptions>();
		configureServices?.Invoke(builder.Services);
		var app = builder.Build();
		app.UseAuthentication();
		app.UseAuthorization();
		app.MapControllers();
		await app.StartAsync();
		return new TestHost(app, app.GetTestClient());
	}

	protected sealed class TestHost(WebApplication app, HttpClient client) : IAsyncDisposable
	{
		public HttpClient Client { get; } = client;
		public async ValueTask DisposeAsync()
		{
			Client.Dispose();
			await app.DisposeAsync();
		}
	}

	protected sealed class RecordingEmailSender : IEmailSender
	{
		public List<(string Recipient, string Body)> Messages { get; } = [];
		public bool Fail { get; set; }
		public string LastToken => Regex.Match(Messages[^1].Body, @"(?m)^[A-Za-z0-9_-]{43}$").Value;
		public Task SendAsync(string recipient, string subject, string body, CancellationToken cancellationToken = default)
		{
			cancellationToken.ThrowIfCancellationRequested();
			if (Fail)
				throw new EmailDeliveryException("Simulated SMTP failure.", new IOException("Test failure."));
			Messages.Add((recipient, body));
			return Task.CompletedTask;
		}
	}
}
